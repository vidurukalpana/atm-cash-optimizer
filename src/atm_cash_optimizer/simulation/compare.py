"""Compare policies: best setting of each, optimizer savings, breakdowns, frontier chart."""

from __future__ import annotations

from pathlib import Path

import pandas as pd
import plotly.express as px
import plotly.graph_objects as go

from atm_cash_optimizer.io import markdown_table
from atm_cash_optimizer.simulation.metrics import network_totals

OPTIMIZER = "optimizer"
WEEKDAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]


def setting_label(policy: str, param: float) -> str:
    """Readable name, e.g. ``threshold 30%``."""
    if policy == "fixed_schedule":
        return f"fixed schedule ({WEEKDAYS[int(param)]})"
    if policy == "threshold":
        return f"threshold {param:.0%}"
    return f"optimizer alpha {param:.2f}"


def best_settings(network: pd.DataFrame) -> pd.DataFrame:
    """The cheapest setting of each policy."""
    return network.loc[network.groupby("policy")["total_cost"].idxmin()].reset_index(drop=True)


def _labels(network: pd.DataFrame) -> list[str]:
    return [setting_label(p, v) for p, v in zip(network["policy"], network["param"], strict=True)]


def savings(best: pd.DataFrame) -> dict[str, float | str]:
    """Cost saving of the best optimizer setting vs the best simple rule."""
    optimizer = best[best["policy"] == OPTIMIZER].iloc[0]
    baselines = best[best["policy"] != OPTIMIZER]
    baseline = baselines.loc[baselines["total_cost"].idxmin()]
    return {
        "optimizer": setting_label(optimizer["policy"], optimizer["param"]),
        "baseline": setting_label(baseline["policy"], baseline["param"]),
        "optimizer_cost": optimizer["total_cost"],
        "baseline_cost": baseline["total_cost"],
        "saving_pct": 100 * (1 - optimizer["total_cost"] / baseline["total_cost"]),
        "optimizer_stockout_rate": optimizer["stockout_rate"],
        "baseline_stockout_rate": baseline["stockout_rate"],
    }


def breakdown(summary: pd.DataFrame, best: pd.DataFrame, by: str) -> pd.DataFrame:
    """Cost and stockout rate of each policy's best setting per ``by`` segment."""
    keep = summary.merge(best[["policy", "param"]], on=["policy", "param"])
    keep = keep[keep[by].notna()]
    grouped = keep.groupby([by, "policy"]).agg(
        machines=("machine_id", "nunique"),
        total_cost=("total_cost", "sum"),
        stockout_days=("stockout_days", "sum"),
        days=("days", "sum"),
    )
    grouped["stockout_rate"] = grouped.pop("stockout_days") / grouped.pop("days")
    return grouped.reset_index()


def frontier_figure(network: pd.DataFrame, track: str) -> go.Figure:
    """Stockout rate vs total cost, one point per policy setting."""
    df = network.assign(setting=_labels(network))
    fig = px.scatter(
        df,
        x="stockout_rate",
        y="total_cost",
        color="policy",
        text="setting",
        title=f"Policy frontier — {track} track (lower and further left is better)",
        labels={
            "stockout_rate": "stockout rate (share of machine-days)",
            "total_cost": "total cost (LKR)",
        },
    )
    fig.update_traces(textposition="top center")
    return fig


def frontier_chart(network: pd.DataFrame, track: str, path: Path) -> None:
    """Save :func:`frontier_figure` as an HTML file."""
    frontier_figure(network, track).write_html(path, include_plotlyjs="cdn")


def results_report(
    track: str, summary: pd.DataFrame, machines: pd.DataFrame, setup: dict[str, str]
) -> str:
    """Markdown text of ``reports/results_<track>.md``."""
    network = network_totals(summary)
    best = best_settings(network)
    result = savings(best)

    columns = [
        "setting",
        "total_cost",
        "visits",
        "emergency_visits",
        "stockout_rate",
        "avg_idle_cash",
        "unmet_withdrawals_lkr",
        "vault_full_days",
    ]
    table = network.assign(setting=_labels(network))[columns]
    table = table.sort_values("total_cost")
    lines = [
        f"# Simulation results — {track} track\n",
        "Generated by `python -m atm_cash_optimizer.simulation.run`. Every policy replays the same "
        "days with the same machines, capacities, no-service days, lead time and emergency rule. "
        "Metrics as defined in `docs/metrics.md` (warmup days excluded).\n",
        "## Setup\n",
        *[f"- {k}: {v}" for k, v in setup.items()],
        "",
        "## Headline\n",
        f"**{result['optimizer']}** costs **{result['saving_pct']:.1f} % less** than the best "
        f"simple rule (**{result['baseline']}**): LKR {result['optimizer_cost']:,.0f} vs "
        f"{result['baseline_cost']:,.0f}. Stockout rate {result['optimizer_stockout_rate']:.2%} vs "
        f"{result['baseline_stockout_rate']:.2%}.\n",
        "## All settings (network totals, cheapest first)\n",
        markdown_table(table, "{:,.3f}"),
        "",
    ]
    machine_info = machines[["machine_id", "machine_type", "location_type"]]
    with_info = summary.merge(machine_info, on="machine_id")
    for by in ("machine_type", "location_type"):
        part = breakdown(with_info, best, by)
        if part.empty:
            continue
        lines += [f"## Best setting of each policy, by {by}\n", markdown_table(part, "{:,.3f}"), ""]
    lines.append(f"Frontier chart: `reports/frontier_{track}.html`.\n")
    return "\n".join(lines)
